package com.switchStatement;

public class Mobile_Q16 {

	public static void main(String[] args) {
		
		int mobile=2;
		
		switch(mobile) {
		
		case 1:
			System.out.println("Wifi");
			break;
		case 2:
			System.out.println("Bluetooth");
			break;
		case 3:
			System.out.println("Mobile Data");
			break;
		case 4:
			System.out.println("Airplane Mode");
			break;
			
		}
	}
}

public class Result_Q19 {
	public static void main(String[] args) {
		
		int marks=97; 
		
		switch(marks) {
		
		case 1:
			System.out.println("Pass");
		break;
		case 2:
			System.out.println("Distinction");
		break;
		case 3:
			System.out.println("Fail");
		break;
		default:
			System.out.println("Invalid Marks ...!");
		
		
		}
	}

}
